/* Convert normalized float32 [0.0 .. 1.0] RGB to RGB565 */
static inline uint16_t rgb_to_rgb565(float r, float g, float b)
{
    if (r < 0.0f) r = 0.0f; else if (r > 1.0f) r = 1.0f;
    if (g < 0.0f) g = 0.0f; else if (g > 1.0f) g = 1.0f;
    if (b < 0.0f) b = 0.0f; else if (b > 1.0f) b = 1.0f;
    uint16_t r5 = (uint16_t)(r * 31.0f + 0.5f);
    uint16_t g6 = (uint16_t)(g * 63.0f + 0.5f);
    uint16_t b5 = (uint16_t)(b * 31.0f + 0.5f);
    return (uint16_t)((r5 << 11) | (g6 << 5) | b5);
}

void board_lcd_draw_pixel(int x, int y, uint16_t color)
{
    if (x >= 0 && x < LCD_WIDTH && y >= 0 && y < LCD_HEIGHT) {
        s_fb[y * LCD_WIDTH + x] = color;
    }
}

void board_lcd_clear(uint16_t color)
{
    uint32_t c32 = ((uint32_t)color << 16) | color;
    volatile uint32_t *p32 = (volatile uint32_t *)s_fb;
    uint32_t n = (LCD_WIDTH * LCD_HEIGHT) / 2;
    for (uint32_t i = 0; i < n; i++) {
        p32[i] = c32;
    }
}

void board_lcd_fill_rect(int x, int y, int w, int h, uint16_t color)
{
    int x1 = x < 0 ? 0 : x;
    int y1 = y < 0 ? 0 : y;
    int x2 = (x + w) > LCD_WIDTH ? LCD_WIDTH : (x + w);
    int y2 = (y + h) > LCD_HEIGHT ? LCD_HEIGHT : (y + h);

    for (int j = y1; j < y2; j++) {
        volatile uint16_t *row = &s_fb[j * LCD_WIDTH];
        for (int i = x1; i < x2; i++) {
            row[i] = color;
        }
    }
}

void board_lcd_draw_rect(int x, int y, int w, int h, uint16_t color, int thickness)
{
    for (int t = 0; t < thickness; t++) {
        /* Top & Bottom horizontal lines */
        for (int i = x; i < x + w; i++) {
            board_lcd_draw_pixel(i, y + t, color);
            board_lcd_draw_pixel(i, y + h - 1 - t, color);
        }
        /* Left & Right vertical lines */
        for (int j = y; j < y + h; j++) {
            board_lcd_draw_pixel(x + t, j, color);
            board_lcd_draw_pixel(x + w - 1 - t, j, color);
        }
    }
}

