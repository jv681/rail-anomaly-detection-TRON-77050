/* Render camera feed onto LCD */
void board_lcd_draw_camera_feed(int x, int y, int w, int h, const float *tensor_f32)
{
    /* Tensor is float32 CHW [3, 320, 320] */
    const float *r_plane = tensor_f32;
    const float *g_plane = tensor_f32 + (320 * 320);
    const float *b_plane = tensor_f32 + (2 * 320 * 320);

    /* Scale 320x320 into w x h on LCD */
    for (int j = 0; j < h; j++) {
        int src_y = (j * 320) / h;
        if (src_y >= 320) src_y = 319;
        int row_offset = src_y * 320;
        volatile uint16_t *fb_row = &s_fb[(y + j) * LCD_WIDTH + x];

        for (int i = 0; i < w; i++) {
            int src_x = (i * 320) / w;
            if (src_x >= 320) src_x = 319;
            int idx = row_offset + src_x;

            float r = r_plane[idx];
            float g = g_plane[idx];
            float b = b_plane[idx];

            fb_row[i] = rgb_to_rgb565(r, g, b);
        }
    }
}

/* Draw live bounding boxes and labels over the camera viewport */
void board_lcd_render_detections(int cam_x, int cam_y, int cam_w, int cam_h, const YoloResult_t *res)
{
    if (!res || res->count <= 0) return;

    for (int i = 0; i < res->count; i++) {
        const YoloDetection_t *d = &res->dets[i];

        /* Scale normalized coordinates (0..320) to LCD viewport */
        int bx1 = cam_x + (int)((d->x1 * cam_w) / 320.0f);
        int by1 = cam_y + (int)((d->y1 * cam_h) / 320.0f);
        int bx2 = cam_x + (int)((d->x2 * cam_w) / 320.0f);
        int by2 = cam_y + (int)((d->y2 * cam_h) / 320.0f);

        int bw = bx2 - bx1;
        int bh = by2 - by1;
        if (bw < 10) bw = 10;
        if (bh < 10) bh = 10;

        /* Highlight in Red */
        board_lcd_draw_rect(bx1, by1, bw, bh, LCD_COLOR_RED, 3);

        /* Label badge */
        char lbl[48];
        snprintf(lbl, sizeof(lbl), "%s %.0f%%", d->class_name, d->confidence * 100.0f);
        int lbl_w = (int)strlen(lbl) * 8 + 6;
        board_lcd_fill_rect(bx1, (by1 >= 20 ? by1 - 18 : by1), lbl_w, 16, LCD_COLOR_RED);
        board_lcd_draw_string(bx1 + 3, (by1 >= 20 ? by1 - 16 : by1 + 2), lbl, LCD_COLOR_WHITE, LCD_COLOR_RED, 1);
    }
}

