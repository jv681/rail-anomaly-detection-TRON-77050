/* Hardware MSP Initialization for LTDC */
void HAL_LTDC_MspInit(LTDC_HandleTypeDef *hltdc)
{
    GPIO_InitTypeDef gpio = {0};

    if (hltdc->Instance == LTDC)
    {
        /* 1. Clocks */
        __HAL_RCC_LTDC_CLK_ENABLE();
        __HAL_RCC_LTDC_FORCE_RESET();
        __HAL_RCC_LTDC_RELEASE_RESET();

        __HAL_RCC_GPIOA_CLK_ENABLE();
        __HAL_RCC_GPIOB_CLK_ENABLE();
        __HAL_RCC_GPIOD_CLK_ENABLE();
        __HAL_RCC_GPIOE_CLK_ENABLE();
        __HAL_RCC_GPIOG_CLK_ENABLE();
        __HAL_RCC_GPIOH_CLK_ENABLE();
        __HAL_RCC_GPIOQ_CLK_ENABLE();

        gpio.Mode      = GPIO_MODE_AF_PP;
        gpio.Pull      = GPIO_NOPULL;
        gpio.Speed     = GPIO_SPEED_FREQ_HIGH;
        gpio.Alternate = GPIO_AF14_LCD;

        /* GPIOA: PA0, PA1, PA2, PA7, PA8, PA15 */
        gpio.Pin = GPIO_PIN_0 | GPIO_PIN_1 | GPIO_PIN_2 | GPIO_PIN_7 | GPIO_PIN_8 | GPIO_PIN_15;
        HAL_GPIO_Init(GPIOA, &gpio);

        /* GPIOB: PB2, PB4, PB11, PB12, PB13, PB14, PB15 */
        gpio.Pin = GPIO_PIN_13 | GPIO_PIN_14 | GPIO_PIN_2 | GPIO_PIN_4 | GPIO_PIN_11 | GPIO_PIN_12 | GPIO_PIN_15;
        HAL_GPIO_Init(GPIOB, &gpio);

        /* GPIOD: PD8, PD9, PD15 */
        gpio.Pin = GPIO_PIN_8 | GPIO_PIN_9 | GPIO_PIN_15;
        HAL_GPIO_Init(GPIOD, &gpio);

        /* GPIOE: PE11 (VSYNC) */
        gpio.Pin = GPIO_PIN_11;
        HAL_GPIO_Init(GPIOE, &gpio);

        /* GPIOG: PG0, PG1, PG6, PG8, PG11, PG12 */
        gpio.Pin = GPIO_PIN_0 | GPIO_PIN_1 | GPIO_PIN_6 | GPIO_PIN_8 | GPIO_PIN_11 | GPIO_PIN_12;
        HAL_GPIO_Init(GPIOG, &gpio);

        /* GPIOH: PH3, PH4, PH6 */
        gpio.Pin = GPIO_PIN_3 | GPIO_PIN_4 | GPIO_PIN_6;
        HAL_GPIO_Init(GPIOH, &gpio);

        /* Reset: PE1 */
        gpio.Pin  = GPIO_PIN_1;
        gpio.Mode = GPIO_MODE_OUTPUT_PP;
        HAL_GPIO_Init(GPIOE, &gpio);
        HAL_GPIO_WritePin(GPIOE, GPIO_PIN_1, GPIO_PIN_SET);

        /* Display Enable: PG13 */
        gpio.Pin  = GPIO_PIN_13;
        gpio.Mode = GPIO_MODE_OUTPUT_PP;
        HAL_GPIO_Init(GPIOG, &gpio);
        HAL_GPIO_WritePin(GPIOG, GPIO_PIN_13, GPIO_PIN_SET);

        /* Backlight & Power: PQ3 (LCD_ONOFF), PQ6 (LCD_BL_CTRL) */
        gpio.Pin  = GPIO_PIN_3 | GPIO_PIN_6;
        gpio.Mode = GPIO_MODE_OUTPUT_PP;
        HAL_GPIO_Init(GPIOQ, &gpio);
        HAL_GPIO_WritePin(GPIOQ, GPIO_PIN_3, GPIO_PIN_SET); /* LCD On */
        HAL_GPIO_WritePin(GPIOQ, GPIO_PIN_6, GPIO_PIN_SET); /* 100% Brightness */
    }
}

/* Handlers to safely absorb any unhandled XSPI or LTDC interrupts */
void XSPI1_IRQHandler(void)
{
    XSPI1->FCR = 0x1F;
    NVIC_ClearPendingIRQ(XSPI1_IRQn);
}

void XSPI2_IRQHandler(void)
{
    XSPI2->FCR = 0x1F;
    NVIC_ClearPendingIRQ(XSPI2_IRQn);
}

void XSPI3_IRQHandler(void)
{
    XSPI3->FCR = 0x1F;
    NVIC_ClearPendingIRQ(XSPI3_IRQn);
}

void LTDC_IRQHandler(void)
{
    HAL_LTDC_IRQHandler(&s_hltdc);
}

void LTDC_ER_IRQHandler(void)
{
    HAL_LTDC_IRQHandler(&s_hltdc);
}

static int s_lcd_ok = 0; /* 1 once LTDC is fully running */

int board_lcd_init(void)
{
    /* ------------------------------------------------------------------ */
    /* Step 0: Silence XSPI1/2 IRQs (XSPI3 is Secure-only — NVIC only)   */
    /* ------------------------------------------------------------------ */
    NVIC_DisableIRQ(XSPI1_IRQn);
    NVIC_DisableIRQ(XSPI2_IRQn);
    NVIC_DisableIRQ(XSPI3_IRQn);
    NVIC_ClearPendingIRQ(XSPI1_IRQn);
    NVIC_ClearPendingIRQ(XSPI2_IRQn);
    NVIC_ClearPendingIRQ(XSPI3_IRQn);
    /* Register writes skipped to avoid bus fault if memory-mapped */
    /* XSPI1->CR &= ~0x001F0000U; XSPI1->FCR = 0x1FU; */
    /* XSPI2->CR &= ~0x001F0000U; XSPI2->FCR = 0x1FU; */

    /* ------------------------------------------------------------------ */
    /* Step 1: LTDC pixel clock via IC16                                   */
    /* Non-fatal: if HAL_RCCEx_PeriphCLKConfig fails, FSBL already set it */
    /* ------------------------------------------------------------------ */
    RCC_PeriphCLKInitTypeDef rcc_clk = {0};
    rcc_clk.PeriphClockSelection                 = RCC_PERIPHCLK_LTDC;
    rcc_clk.LtdcClockSelection                   = RCC_LTDCCLKSOURCE_IC16;
    rcc_clk.ICSelection[RCC_IC16].ClockSelection = RCC_ICCLKSOURCE_PLL4;
    rcc_clk.ICSelection[RCC_IC16].ClockDivider   = 2;
    /* best-effort — non-fatal if secure world has already locked the clock */
    (void)HAL_RCCEx_PeriphCLKConfig(&rcc_clk);

    /* ------------------------------------------------------------------ */
    /* Step 2: LTDC controller init with RK050HR18 timings                 */
    /* ------------------------------------------------------------------ */
    s_hltdc.Instance = LTDC;
    s_hltdc.Init.HSPolarity = LTDC_HSPOLARITY_AL;
    s_hltdc.Init.VSPolarity = LTDC_VSPOLARITY_AL;
    s_hltdc.Init.DEPolarity = LTDC_DEPOLARITY_AL;
    s_hltdc.Init.PCPolarity = LTDC_PCPOLARITY_IPC;

    s_hltdc.Init.HorizontalSync     = (uint32_t)RK050HR18_HSYNC - 1U;
    s_hltdc.Init.AccumulatedHBP     = (uint32_t)RK050HR18_HSYNC + (uint32_t)RK050HR18_HBP - 1U;
    s_hltdc.Init.AccumulatedActiveW = (uint32_t)RK050HR18_HSYNC + LCD_WIDTH + (uint32_t)RK050HR18_HBP - 1U;
    s_hltdc.Init.TotalWidth         = (uint32_t)RK050HR18_HSYNC + LCD_WIDTH + (uint32_t)RK050HR18_HBP + RK050HR18_HFP - 1U;

    s_hltdc.Init.VerticalSync       = (uint32_t)RK050HR18_VSYNC - 1U;
    s_hltdc.Init.AccumulatedVBP     = (uint32_t)RK050HR18_VSYNC + (uint32_t)RK050HR18_VBP - 1U;
    s_hltdc.Init.AccumulatedActiveH = (uint32_t)RK050HR18_VSYNC + LCD_HEIGHT + (uint32_t)RK050HR18_VBP - 1U;
    s_hltdc.Init.TotalHeigh         = (uint32_t)RK050HR18_VSYNC + LCD_HEIGHT + (uint32_t)RK050HR18_VBP + RK050HR18_VFP - 1U;

    s_hltdc.Init.Backcolor.Red   = 0x00;
    s_hltdc.Init.Backcolor.Green = 0x00;
    s_hltdc.Init.Backcolor.Blue  = 0x00;

    if (HAL_LTDC_Init(&s_hltdc) != HAL_OK) {
        return -2; /* LCD unavailable — system continues without display */
    }

    /* ------------------------------------------------------------------ */
    /* Step 3: Layer 0 — full-screen RGB565 framebuffer                    */
    /* ------------------------------------------------------------------ */
    LTDC_LayerCfgTypeDef layer_cfg = {0};
    layer_cfg.WindowX0        = 0;
    layer_cfg.WindowX1        = LCD_WIDTH;
    layer_cfg.WindowY0        = 0;
    layer_cfg.WindowY1        = LCD_HEIGHT;
    layer_cfg.PixelFormat     = LTDC_PIXEL_FORMAT_RGB565;
    layer_cfg.Alpha           = 255;
    layer_cfg.Alpha0          = 0;
    layer_cfg.BlendingFactor1 = LTDC_BLENDING_FACTOR1_PAxCA;
    layer_cfg.BlendingFactor2 = LTDC_BLENDING_FACTOR2_PAxCA;
    layer_cfg.FBStartAdress   = (uint32_t)s_lcd_framebuf;
    layer_cfg.ImageWidth      = LCD_WIDTH;
    layer_cfg.ImageHeight     = LCD_HEIGHT;
    layer_cfg.Backcolor.Red   = 0;
    layer_cfg.Backcolor.Green = 0;
    layer_cfg.Backcolor.Blue  = 0;

    if (HAL_LTDC_ConfigLayer(&s_hltdc, &layer_cfg, 0) != HAL_OK) {
        return -3;
    }

    /* Step 4: Enable LTDC */
    __HAL_LTDC_ENABLE(&s_hltdc);

    /* Step 5: Paint initial UI */
    board_lcd_draw_ui_base();

    s_lcd_ok = 1;
    return 0;
}

/* Returns 1 if LCD initialized successfully, 0 if unavailable */
int board_lcd_is_ready(void) { return s_lcd_ok; }
